"""Turn preprocess.json (from train_csi.py) into main/preprocess_config.h for the ESP32.

    python tools/gen_preprocess_h.py models/checkpoints/preprocess.json main/preprocess_config.h
"""
import json
import sys
from pathlib import Path

src = Path(sys.argv[1] if len(sys.argv) > 1 else "models/checkpoints/preprocess.json")
dst = Path(sys.argv[2] if len(sys.argv) > 2 else "main/preprocess_config.h")
p = json.loads(src.read_text())

bins = [[int(i) for i in b] for b in p["subcarrier_bins"]]
flat = [i for b in bins for i in b]
offsets = [0]
for b in bins:
    offsets.append(offsets[-1] + len(b))
labels = p["labels"]

lines = [
    "/* Generated by tools/gen_preprocess_h.py from preprocess.json - do not edit. */",
    "#pragma once",
    "#include <stdint.h>",
    "",
    f"#define PREP_WINDOW      {int(p['window_packets'])}",
    f"#define PREP_STRIDE      {int(p['stride_packets'])}",
    f"#define PREP_NUM_BINS    {len(bins)}",
    f"#define PREP_NUM_LABELS  {len(labels)}",
    f"#define PREP_SCALE       {float(p['scale'])!r}f",
    f"#define PREP_DETREND     {1 if p['detrend'] else 0}",
    "",
    "/* bin b averages subcarriers PREP_BIN_IDX[PREP_BIN_OFF[b] .. PREP_BIN_OFF[b+1]-1] */",
    f"static const uint16_t PREP_BIN_IDX[] = {{{', '.join(map(str, flat))}}};",
    f"static const uint16_t PREP_BIN_OFF[] = {{{', '.join(map(str, offsets))}}};",
    "",
    "static const char *const PREP_LABELS[] = {" + ", ".join(json.dumps(l) for l in labels) + "};",
    "",
]
dst.write_text("\n".join(lines))
print(f"wrote {dst}: window={p['window_packets']} stride={p['stride_packets']} "
      f"bins={len(bins)} labels={labels}")
